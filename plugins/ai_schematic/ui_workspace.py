"""按 UI 原型组织原生窗口；此模块只构建控件，不发送网络或画图请求。"""
import os

from PySide6.QtCore import Qt
from PySide6.QtGui import QKeySequence, QShortcut
from PySide6.QtWidgets import (QComboBox, QFrame, QGridLayout, QGroupBox,
    QHBoxLayout, QLabel, QLineEdit, QPlainTextEdit, QProgressBar, QPushButton,
    QScrollArea, QStackedWidget, QTabWidget, QTextBrowser, QToolButton,
    QVBoxLayout, QWidget)

from .ai_service import DEFAULT_URL
from .ui_theme import STYLESHEET


def label(text, name="muted", *, wrap=True):
    value = QLabel(text)
    value.setTextFormat(Qt.TextFormat.PlainText)
    value.setObjectName(name)
    value.setWordWrap(wrap)
    return value


def build_workspace(w):
    """保留状态机入口，换成导航、对话、统一输入框和设计上下文。"""
    w.setStyleSheet(STYLESHEET)
    w.resize(500, 740)
    w.setMinimumSize(420, 600)
    shell = QWidget()
    shell.setObjectName("shell")
    frame = QHBoxLayout(shell)
    frame.setContentsMargins(0, 0, 0, 0)
    frame.setSpacing(0)
    # 辅助面板使用顶部页签，不保留隐藏的大侧栏结构。
    w.sidebar = QFrame()
    w.sidebar.hide()
    w.nav_buttons = []
    main = QWidget()
    outer = QVBoxLayout(main)
    outer.setContentsMargins(10, 8, 10, 8)
    top = QFrame()
    top.setObjectName("topbar")
    top_row = QHBoxLayout(top)
    top_row.setContentsMargins(0, 0, 0, 12)
    w.breadcrumb = label("RF EDA · AI 设计助手", "sectionTitle")
    top_row.addWidget(w.breadcrumb, 1)
    top_row.addWidget(label("0.2.4", wrap=False))
    top_row.addWidget(w.button("manage", "设置", w.open_management))
    outer.addWidget(top)
    w.tabs = QTabWidget()
    w.tabs.tabBar().show()
    design, tasks_page, connection_page = QWidget(), QWidget(), QWidget()
    for page, title in ((design, "设计助手"), (tasks_page, "任务与版本"), (connection_page, "服务连接")):
        if page is not design:
            scroll = QScrollArea()
            scroll.setWidgetResizable(True)
            scroll.setWidget(page)
            w.tabs.addTab(scroll, title)
        else:
            w.tabs.addTab(page, title)
    w.tabs.currentChanged.connect(w.navigation_changed)
    outer.addWidget(w.tabs, 1)
    frame.addWidget(main, 1)

    root = QVBoxLayout(design)
    root.setContentsMargins(0, 5, 0, 0)
    heading = QHBoxLayout()
    w.design_heading = label("开始一个新设计", "pageHeading")
    heading.addWidget(w.design_heading, 1)
    heading.addWidget(w.button("new", "新设计", w.new_design))
    heading.addWidget(w.button("finish", "结束本轮 ↗", w.finish_round))
    root.addLayout(heading)
    w.target_label = label("提交前核验目标图纸", "targetLabel")
    root.addWidget(w.target_label)
    columns = QHBoxLayout()
    columns.setSpacing(22)
    root.addLayout(columns, 1)
    center = QVBoxLayout()
    columns.addLayout(center, 1)
    w.conversation = QTextBrowser()
    w.conversation.setObjectName("conversation")
    w.conversation.setMinimumHeight(86)
    w.conversation.setOpenExternalLinks(False)
    w.conversation.setOpenLinks(False)
    center.addWidget(w.conversation, 1)

    # 运行状态和命令行事件直接留在设计页面，长任务不需要换页查看。
    activity_header = QHBoxLayout()
    w.activity_toggle = QToolButton()
    w.activity_toggle.setText("日志")
    w.activity_toggle.setToolButtonStyle(Qt.ToolButtonStyle.ToolButtonTextBesideIcon)
    w.activity_toggle.setArrowType(Qt.ArrowType.DownArrow)
    w.activity_toggle.setCheckable(True)
    w.activity_toggle.setChecked(False)
    activity_header.addWidget(w.activity_toggle)
    w.status = label("准备就绪 · 上传技术协议，或直接描述设计目标")
    w.status.setTextFormat(Qt.TextFormat.PlainText)
    w.status.setMaximumHeight(54)
    activity_header.addWidget(w.status, 1)
    center.addLayout(activity_header)
    w.log = QPlainTextEdit()
    w.log.setObjectName("eventLog")
    w.log.setReadOnly(True)
    w.log.setMaximumBlockCount(5000)
    w.log.setFixedHeight(70)
    w.log.hide()
    w.activity_toggle.toggled.connect(w.log.setVisible)
    w.activity_toggle.toggled.connect(lambda opened: w.activity_toggle.setArrowType(
        Qt.ArrowType.UpArrow if opened else Qt.ArrowType.DownArrow))
    center.addWidget(w.log)
    w.progress = QProgressBar()
    w.progress.setRange(0, 1)
    w.progress.setValue(0)
    w.progress.setTextVisible(False)
    w.progress.setFixedHeight(4)
    center.addWidget(w.progress)
    apply = w.button("apply", "更新原理图", w.update_schematic)
    apply.setProperty("primary", True)
    apply.setToolTip("首轮与反馈轮统一手动应用：清空当前图页并按最新 Graph IR 重绘")
    center.addWidget(apply)

    composer = QFrame()
    composer.setObjectName("composer")
    compose = QVBoxLayout(composer)
    compose.setContentsMargins(10, 8, 10, 8)
    mode_row = QHBoxLayout()
    w.input_mode = QComboBox()
    w.input_mode.addItem("设计要求 / 补充说明", "create")
    w.input_mode.addItem("基于当前成功图反馈 / 咨询", "feedback")
    mode_row.addWidget(w.input_mode, 1)
    w.run_name = QLineEdit()
    w.run_name.setMaxLength(100)
    w.run_name.setPlaceholderText("任务名称（可选）")
    w.run_name.setMaximumWidth(130)
    mode_row.addWidget(w.run_name)
    compose.addLayout(mode_row)
    w.attachment_row = QWidget()
    attachment = QHBoxLayout(w.attachment_row)
    attachment.setContentsMargins(0, 0, 0, 0)
    w.path = QLineEdit()
    w.path.setReadOnly(True)
    w.path.setPlaceholderText("未选择附件 · 可仅使用文字")
    attachment.addWidget(w.path, 1)
    attachment.addWidget(w.button("remove_file", "移除", w.remove_file))
    compose.addWidget(w.attachment_row)
    w.user_text, w.feedback = QPlainTextEdit(), QPlainTextEdit()
    for editor in (w.user_text, w.feedback):
        editor.setObjectName("instruction")
        editor.setMinimumHeight(64)
        editor.setMaximumHeight(84)
    w.user_text.setPlaceholderText("描述你要设计的链路；也可以上传技术协议，并在这里补充要求…")
    w.feedback.setPlaceholderText("描述修改要求、提出咨询，或补充上一轮问题…")
    w.editor_stack = QStackedWidget()
    w.editor_stack.addWidget(w.user_text)
    w.editor_stack.addWidget(w.feedback)
    w.editor_stack.setMaximumHeight(84)
    compose.addWidget(w.editor_stack)
    w.choices = QComboBox()
    w.choices.setPlaceholderText("后端建议 · 选择只填入草稿，不自动提交")
    compose.addWidget(w.choices)
    w.selection_label = label("反馈只依据后端版本；人工改图不参与，下次更新将清空旧图。")
    compose.addWidget(w.selection_label)
    w.feedback_toolbar = QWidget()
    feedback_tools = QHBoxLayout(w.feedback_toolbar)
    feedback_tools.setContentsMargins(0, 0, 0, 0)
    feedback_tools.addWidget(w.button("composer_new_feedback", "继续反馈", w.new_feedback))
    feedback_tools.addStretch(1)
    compose.addWidget(w.feedback_toolbar)
    tools = QHBoxLayout()
    tools.addWidget(w.button("word", "＋ 技术协议", lambda: w.choose_file("word")))
    w.input_hint = label("仅 Word / Word＋文字 / 仅文字")
    tools.addWidget(w.input_hint, 1)
    for key, title, callback in (("start", "开始设计  ↑", w.start_design),
                                 ("feedback", "提交反馈  ↑", w.submit_feedback)):
        b = w.button(key, title, callback)
        b.setProperty("primary", True)
        tools.addWidget(b)
    compose.addLayout(tools)
    center.addWidget(composer)
    foot = QHBoxLayout()
    foot.addWidget(label("Ctrl + Enter 发送"), 1)
    w.char_count = label("0 / 20000", wrap=False)
    foot.addWidget(w.char_count)
    center.addLayout(foot)

    # 保留占位属性供旧窗口控制代码识别；不构建隐藏的上下文工具栏。
    w.context_panel = QFrame()
    w.context_panel.hide()
    tasks = QVBoxLayout(tasks_page)
    task_heading = QHBoxLayout()
    task_heading.addWidget(label("任务与版本", "pageHeading"), 1)
    task_heading.addWidget(w.button("clear_records", "清除任务记录", w.clear_records))
    tasks.addLayout(task_heading)
    tasks.addWidget(label("恢复原任务，查看本轮操作和当前成功图。运行日志在设计助手内实时显示。"))
    w.task_summary = label("尚未提交任务")
    w.task_summary.setTextFormat(Qt.TextFormat.PlainText)
    tasks.addWidget(w.task_summary)
    w.version_label = label("未生成", "version")
    w.input_summary = label("文字 / 技术协议")
    w.stage_detail = label("尚未开始")
    w.stage_labels = []
    tasks.addWidget(w.version_label)
    tasks.addWidget(w.input_summary)
    tasks.addWidget(w.stage_detail)
    w.add_buttons(tasks, [("resume", "继续 / 恢复", w.resume),
        ("resume_id", "按 ID 恢复…", w.resume_by_id),
        ("operation_report", "本轮报告", lambda: w.download_report(False)),
        ("export", "保存 Graph IR", w.export_graph)])
    w.add_buttons(tasks, [("json", "导入 Graph IR", w.import_local_graph),
        ("history", "版本记录", w.show_history)])
    w.add_buttons(tasks, [("current_report", "当前设计报告", lambda: w.download_report(True)),
        ("requirements", "设计指标要求", w.show_requirements)])
    feedback_tools = QGroupBox("画布更新")
    fb = QVBoxLayout(feedback_tools)
    fb.addWidget(label("首轮和反馈都只生成结果；点击设计页的更新按钮后才清空并重绘当前图页。"))
    w.add_buttons(fb, [("new_feedback", "继续反馈", w.new_feedback),
        ("interface_help", "清空图页接口说明", w.show_interface_help), ("verify", "处理未确认操作", w.verify_canvas)])
    tasks.addWidget(feedback_tools)
    recovery = QGroupBox("会话工具")
    recovery_layout = QVBoxLayout(recovery)
    w.add_buttons(recovery_layout, [("bind", "切换图纸会话", w.bind_current),
        ("reload", "重读会话", w.reload_session)])
    tasks.addWidget(recovery)
    tasks.addStretch(1)

    # 连接设置和已有管理接口继续使用原生控件与工作线程。
    connection = QVBoxLayout(connection_page)
    connection.addWidget(label("连接你的 AI 服务", "pageHeading"))
    connection.addWidget(label("连接运行在本机或局域网的 AI-EDA 后端。地址不带 /api/v1。"))
    card = QGroupBox("AI 服务")
    form = QGridLayout(card)
    w.endpoint = QLineEdit(os.environ.get("KICAD_AI_SERVICE_URL") or w.settings.value("service_url", DEFAULT_URL))
    w.token = QLineEdit(os.environ.get("AI_EDA_API_KEY", ""))
    w.token.setEchoMode(QLineEdit.EchoMode.Password)
    w.token.setPlaceholderText("可选服务令牌，仅在本窗口内存保留")
    form.addWidget(label("服务根地址"), 0, 0)
    form.addWidget(w.endpoint, 0, 1)
    form.addWidget(w.button("connect", "检测连接", w.test_connection), 0, 2)
    form.addWidget(label("访问令牌"), 1, 0)
    form.addWidget(w.token, 1, 1, 1, 2)
    form.setColumnStretch(1, 1)
    connection.addWidget(card)
    connection.addWidget(label("服务令牌与模型厂商 API Key、独立管理令牌分开管理。切换服务会清除旧服务令牌。"))
    connection.addWidget(label("模型厂商 / KEY / 运行参数：使用顶部“设置”。\n符号库暂存构建与 Neo4j 发布：使用下方“符号知识库”。"))
    w.service_summary = label("服务尚未检测")
    connection.addWidget(w.service_summary)
    connection.addWidget(w.button("knowledge", "符号知识库", lambda: w.open_management(1)))
    connection.addStretch(1)

    footer = QHBoxLayout()
    footer.addWidget(w.button("stop", "停止等待", w.stop_waiting))
    w.buttons["stop"].setToolTip("停止客户端等待，后端继续执行，可恢复原任务")
    footer.addWidget(label("任务自动保存"), 1)
    footer.addWidget(w.button("clear_chat", "清空对话", w.clear_conversation))
    footer.addWidget(w.button("clear", "清空日志", w.log.clear))
    footer.addWidget(w.button("close", "关闭", w.close))
    outer.addLayout(footer)
    w.setCentralWidget(shell)
    w.send_shortcut = QShortcut(QKeySequence("Ctrl+Return"), w)
    w.send_shortcut.activated.connect(lambda: w.invoke(w.send_message))
    w.input_mode.currentIndexChanged.connect(w.composer_changed)
    w.path.textChanged.connect(w.render_busy)
    w.navigation_changed(0)
